//! D38: markpad-grammars 构建脚本——编译全部语法 C/C++ 目标码进本 cdylib，
//! 并为每个 tree_sitter_* 入口符号生成 #[no_mangle] 导出包装。
//! 共享编排经 #[path] 引用主 crate 的 grammar_catalog.rs（D38 §5.2）。
#[path = "../grammar_catalog.rs"]
mod catalog;

use std::path::Path;

fn main() {
    // cwd = 本 crate 目录，语法源码在上级 src-tauri/grammars/
    let grammars_dir = Path::new("../grammars");
    if !grammars_dir.exists() {
        panic!("D38: grammars/ not found — run python scripts/download_grammars_git.py first");
    }

    // export_suffix="_impl"：parser.c 内 tree_sitter_xxx 编译期改名为
    // tree_sitter_xxx_impl，包装函数以原名导出并调用 _impl。若不改名，
    // 包装函数体内对同名符号的未定义引用会被链接器解析到包装自身，形成无限递归。
    for (name, dir, subpath, c_symbol) in catalog::GRAMMARS {
        catalog::compile_grammar(name, &grammars_dir.join(dir), subpath, c_symbol, "_impl");
    }

    generate_exports();

    // C++ scanner 运行时随本 DLL 链接（msvc 由 /MT obj 内嵌 /DEFAULTLIB 解析）
    catalog::link_cpp_runtime();
}

/// 生成 OUT_DIR/grammar_exports.rs：每语法一对「raw 声明 + 原名导出包装」。
fn generate_exports() {
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("grammar_exports.rs");
    let mut content = String::new();
    content.push_str("// @generated by grammars-cdylib/build.rs (D38)\n\nmod raw {\n");
    for (_, _, _, c_symbol) in catalog::GRAMMARS {
        content.push_str(&format!(r#"    extern "C" {{ pub fn {c_symbol}_impl() -> *const (); }}
"#));
    }
    content.push_str("}\n\n");
    for (_, _, _, c_symbol) in catalog::GRAMMARS {
        content.push_str(&format!(
            r#"#[no_mangle]
pub extern "C" fn {c_symbol}() -> *const () {{ unsafe {{ raw::{c_symbol}_impl() }} }}
"#
        ));
    }
    std::fs::write(&dest_path, &content).unwrap();
}
